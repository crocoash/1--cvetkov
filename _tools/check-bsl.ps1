# Дешёвая структурная проверка модулей .bsl перед снимком.
#
# ЗАЧЕМ: Конфигуратора на этой машине нет, синтаксическую проверку (F7) выполнить
# нечем, а ошибка компиляции выясняется только после круга push -> pull -> загрузка
# конфигурации. Реальный случай: в модуль добавили функцию с именем, которое уже
# было, — модуль перестал инициализироваться целиком, и вместе с ним замолчал бот.
#
# BSL Language Server этот класс ошибок НЕ ловит (проверено на той самой сломанной
# версии: 225 замечаний, про дубль метода — ни одного). Поэтому проверка своя и
# намеренно узкая: только то, что гарантированно валит компиляцию.
#
#   1) два определения процедуры/функции с одним именем в одном модуле;
#   2) непарные Процедура/КонецПроцедуры, Функция/КонецФункции.
#
# Проверяются только изменённые в рабочей копии .bsl — на всей конфигурации это
# тысячи файлов и минуты времени.
#
# Использование:
#   pwsh -NoProfile -File _tools/check-bsl.ps1            # изменённые файлы
#   pwsh -NoProfile -File _tools/check-bsl.ps1 -Все       # вся конфигурация
#
# Код возврата: 0 — чисто, 1 — есть ошибки.

param([switch]$Все)

$ErrorActionPreference = "Stop"
$git = "C:\Program Files\Git\cmd\git.exe"
if (-not (Test-Path $git)) { $git = "git" }

$root = Split-Path -Parent $PSScriptRoot
Set-Location $root

if ($Все) {
    $файлы = Get-ChildItem -Path $root -Filter "*.bsl" -Recurse -File | ForEach-Object { $_.FullName }
} else {
    # Изменённые и новые, включая уже проиндексированные
    # core.quotepath=false — иначе git отдаёт кириллицу в путях эскейпами
    # (\320\242...) и файл по такому пути не находится
    $список = & $git -c core.quotepath=false status --porcelain
    $файлы = @()
    foreach ($строка in $список) {
        if (-not $строка) { continue }
        $путь = $строка.Substring(3).Trim('"')
        # Переименование: "старое -> новое"
        if ($путь -match "->") { $путь = ($путь -split "->")[-1].Trim().Trim('"') }
        if ($путь -like "*.bsl") {
            $полный = Join-Path $root $путь
            if (Test-Path $полный) { $файлы += $полный }
        }
    }
}

if (-not $файлы -or $файлы.Count -eq 0) {
    Write-Host "Модулей .bsl для проверки нет."
    exit 0
}

# Имена, занятые самой платформой: назвать так процедуру или функцию нельзя,
# модуль перестаёт компилироваться целиком — ровно как при дубле имени.
# Поймано 09.08.2026: обработчик HTTP-сервиса назвали «Выполнить», и вместе
# с модулем сервиса замолчал вебхук, а значит и кнопки бота в чатах.
# Список намеренно короткий — только глобальные функции, которые реально
# просятся в имя своей процедуры. Расширять по мере укусов.
$занятыеИмена = @(
    "Выполнить", "Вычислить", "Сообщить", "Формат", "Строка", "Число", "Дата",
    "Булево", "Тип", "ТипЗнч", "Лев", "Прав", "Сред", "СтрДлина", "СтрЗаменить",
    "СтрНайти", "СокрЛП", "СокрЛ", "СокрП", "Найти", "Окр", "Цел", "Макс", "Мин",
    "ВРег", "НРег", "ТРег", "ПустаяСтрока", "ЗначениеЗаполнено", "ТекущаяДата",
    "Символ", "КодСимвола", "Массив", "Структура", "Соответствие", "Новый"
)

$всегоОшибок = 0

foreach ($файл in $файлы) {

    $строки = Get-Content -LiteralPath $файл -Encoding UTF8
    $имена = @{}
    $ошибки = @()
    $открытоПроцедур = 0
    $открытоФункций  = 0
    $номер = 0

    foreach ($строка in $строки) {

        $номер++
        # Комментарии не считаем: "// Функция ..." в описании — обычное дело
        $код = ($строка -replace "//.*$", "")

        if ($код -match "^\s*(Процедура|Function|Функция|Procedure)\s+([A-Za-z0-9_\u0400-\u04FF]+)\s*\(") {
            $вид = $matches[1]
            $имя = $matches[2]

            if ($имена.ContainsKey($имя)) {
                $ошибки += "  строка $номер : имя '$имя' уже определено в строке $($имена[$имя]) — модуль не скомпилируется"
            } else {
                $имена[$имя] = $номер
            }

            if ($занятыеИмена -contains $имя) {
                $ошибки += "  строка $номер : имя '$имя' занято платформой — модуль не скомпилируется, переименуйте"
            }

            if ($вид -eq "Процедура" -or $вид -eq "Procedure") { $открытоПроцедур++ } else { $открытоФункций++ }
        }
        elseif ($код -match "^\s*(КонецПроцедуры|EndProcedure)\s*$") { $открытоПроцедур-- }
        elseif ($код -match "^\s*(КонецФункции|EndFunction)\s*$")    { $открытоФункций-- }
    }

    if ($открытоПроцедур -ne 0) {
        $ошибки += "  Процедура/КонецПроцедуры не сходятся: разница $открытоПроцедур"
    }
    if ($открытоФункций -ne 0) {
        $ошибки += "  Функция/КонецФункции не сходятся: разница $открытоФункций"
    }

    if ($ошибки.Count -gt 0) {
        $всегоОшибок += $ошибки.Count
        Write-Host ($файл.Replace($root, "").TrimStart([char]92, [char]47)) -ForegroundColor Red
        foreach ($о in $ошибки) { Write-Host $о -ForegroundColor Red }
    }
}

if ($всегоОшибок -eq 0) {
    Write-Host "Модули .bsl: проверено $($файлы.Count), ошибок нет." -ForegroundColor Green
    exit 0
}

Write-Host ""
Write-Host "НАЙДЕНО ОШИБОК: $всегоОшибок. Загружать такую конфигурацию нельзя." -ForegroundColor Red
exit 1
