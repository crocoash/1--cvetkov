#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Предпросмотр макета РезервHTML без 1С и без базы.

Собирает страницу из блоков макета так же, как это делает
ОбщийМодуль.БИАС (см. БлокиОплатыHTML / ПанельСчетаHTML), и подставляет
тестовые данные. Нужен, чтобы смотреть и править вид счёта на маке —
здесь нет ни Конфигуратора, ни базы, а круг «push → pull → загрузка
конфигурации» стоит дорого.

    python3 _tools/preview-reserve.py out.html

Данные в предпросмотре — тестовые: счёт ФОП Цветков, сумма 1 грн,
payload НБУ тот же, что стоял в shop/bank_choice_test.html. Файл годится
и как тестовая страница на сайте: логика выбора банка в нём ровно та,
которую увидит покупатель.

QR рисуется модулем segno, если он установлен; без него блок QR просто
не выводится (на вид счёта это не влияет).
"""

import base64
import io
import os
import re
import sys

МАКЕТ = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "Documents", "ЗаказПокупателя", "Templates", "РезервHTML", "Ext", "Template.txt",
)

# Тестовый счёт: 1 грн, подтверждать платёж не нужно.
ПОЛУЧАТЕЛЬ = "ФОП Цветков Ігор Миколайович"
IBAN = "UA263052990000026006025906874"
ЕГРПОУ = "2357912458"
НАЗНАЧЕНИЕ = "Тест вибору банку"
СУММА = "1"


def payload_нбу():
    """Тот же формат, что складывает Справочники.БанковскиеСчета.NBU_QR_*."""
    поля = [
        "BCD", "002", "1", "UCT", "",
        ПОЛУЧАТЕЛЬ, IBAN, "UAH1.00", ЕГРПОУ, "", "", НАЗНАЧЕНИЕ,
    ]
    текст = "\n".join(поля)
    return текст, base64.urlsafe_b64encode(текст.encode("utf-8")).decode().rstrip("=")


def qr_base64(текст):
    try:
        import segno
    except ImportError:
        return ""

    буфер = io.BytesIO()
    segno.make(текст, error="m").save(буфер, kind="png", scale=6, border=1)
    return base64.b64encode(буфер.getvalue()).decode()


def блоки_макета():
    исходник = io.open(МАКЕТ, encoding="utf-8-sig").read()
    части = re.split(r"<!--БЛОК:([^>]+?)-->", исходник)
    return {части[i].strip(): части[i + 1] for i in range(1, len(части), 2)}


def собрать():
    Б = блоки_макета()

    def блок(имя, **значения):
        текст = Б[имя]
        for ключ, значение in значения.items():
            текст = текст.replace("{{%s}}" % ключ, str(значение))
        return текст

    текст_qr, payload = payload_нбу()
    ссылка = "https://bank.gov.ua/qr/" + payload
    картинка = qr_base64(текст_qr)

    строки = [
        ("1", "Готово", "pill--done", "Тест", "Тестовий товар", "—", "1", "1", "1"),
    ]
    таблица = "".join(
        блок("Строка", КлассСтроки="", Номер=номер, Фото=Б["ФотоЗаглушка"],
             КлассПилюли=класс, Готовность=готовность, ЦеноваяГруппа=группа,
             СсылкаСайта="https://cvetkovtm.com/", Номенклатура=товар,
             Характеристика=характеристика, Количество=количество,
             Цена=цена, Сумма=сумма)
        for номер, готовность, класс, группа, товар, характеристика, количество, цена, сумма in строки
    )

    итоги = "".join(
        блок("ИтогиРяд", Класс=класс, Метка=метка, Значение=значение)
        for класс, метка, значение in [
            ("", '<span class="dot dot--done"></span>Готово', "1 грн"),
            ("sumrow--total", "Разом", "1 грн"),
        ]
    )

    панель = блок(
        "Панель", Актив=" is-active", Ид="p1", ЗаголовокПечати="Переказ на IBAN",
        Вариант="Переказ на рахунок ФОП", Расчет="тестовий рахунок · 1 грн",
        Примечание="до зарахування", Сумма=СУММА, Разбивка="",
        Реквизиты=блок("РеквизитыСтруктур", Получатель=ПОЛУЧАТЕЛЬ, IBAN=IBAN,
                       ЕГРПОУ=ЕГРПОУ, Назначение=НАЗНАЧЕНИЕ,
                       ДатаСчета="тест"),
        QR=блок("QRБлок", QRBase64=картинка) if картинка else "",
        Кнопка=блок("КнопкаБанк", URL=ссылка),
    )

    return (
        блок("Шапка", ДатаОбновления="щойно", КодКлиента="ТЕСТ")
        + блок("ЗаказНачало",
               Заголовок="Тест вибору банку — 1 грн, підтверджувати не треба",
               ДатаЗаказа="—", СуммаЗаказа="1", Позиций="1")
        + таблица
        + Б["ЗаказКонец"]
        + Б["ИтогиНачало"] + итоги + блок("ИтогиКонец", Кнопка="")
        + блок("СчетНачало", Табы="")
        + панель
        + Б["СчетКонец"]
        + Б["Подвал"]
    )


if __name__ == "__main__":
    путь = sys.argv[1] if len(sys.argv) > 1 else "reserve-preview.html"
    страница = собрать()
    io.open(путь, "w", encoding="utf-8", newline="\n").write(страница)
    print("%s — %d символов" % (путь, len(страница)))
